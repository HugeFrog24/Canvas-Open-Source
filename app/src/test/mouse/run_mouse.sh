#!/bin/bash
# Mouse Y-axis harness (MOUSE.md). Runs in canvas-mouse-harness:local (Dockerfile.mouse):
#
#   git show 5c0b41b^:app/src/main/java/com/tgc/sky/GameActivity.java \
#       > app/src/test/mouse/out/canvas-1.7.2/GameActivity.java        # optional third side
#   MSYS_NO_PATHCONV=1 docker run --rm -v "$PWD/app/src:/repo:ro" \
#     -v "C:/Users/admin/Desktop/sky-decoded/0.34.5/smali_classes3/com/tgc/sky:/stock:ro" \
#     -v "$PWD/app/src/test/mouse/out:/out" canvas-mouse-harness:local bash /repo/test/mouse/run_mouse.sh
#   optional fourth side: -v "C:/Users/admin/Desktop/sky-decoded/0.35.1/smali_classes3/com/tgc/sky:/stock2:ro"
#
# Decompiles stock Sky's GameActivity.smali with jadx (read-only input, output in
# /out), extracts the same mouse methods verbatim from it, from Canvas's
# GameActivity.java (HEAD) and, if present, from Canvas 1.7.2 (before #45),
# compiles them against the stubs in harness/, and runs Main.
#   PATCHED=1: the HEAD side comes from a copy with mouse-log.patch applied
#              (checks the patch compiles and shows the lines it would log).
set -eu
M=/repo/test/mouse
OUT=/out
GEN=$OUT/gen
HEAD_SRC=${HEAD_SRC_OVERRIDE:-/repo/main/java/com/tgc/sky/GameActivity.java}  # override: e.g. /out/fixed/GameActivity.java
OLD_SRC=$OUT/canvas-1.7.2/GameActivity.java
STOCK_SRC=$OUT/stock-0.34.5/sources/com/tgc/sky/GameActivity.java
STOCK2_SRC=$OUT/stock-0.35.1/sources/com/tgc/sky/GameActivity.java  # if /stock2 is mounted
HEAD_EXTRA=""

[ -f "$STOCK_SRC" ] || jadx -q --no-res -d $OUT/stock-0.34.5 /stock/GameActivity.smali
[ -d /stock2 ] && { [ -f "$STOCK2_SRC" ] || jadx -q --no-res -d $OUT/stock-0.35.1 /stock2/GameActivity.smali; }

if [ "${PATCHED:-0}" = 1 ]; then
    rm -rf $OUT/patched && mkdir -p $OUT/patched/app/src/main/java/com/tgc/sky
    cp $HEAD_SRC $OUT/patched/app/src/main/java/com/tgc/sky/
    patch -s -d $OUT/patched -p1 < $M/mouse-log.patch
    HEAD_SRC=$OUT/patched/app/src/main/java/com/tgc/sky/GameActivity.java
    HEAD_EXTRA="logMouseEvent"
fi

# Methods taken from every side; MouseBase supplies everything else they call.
COMMON="isSony isDualShock isDualSense isGamepadEvent getDeviceVendorId getDeviceProductId isHardwareMouseEvent
        isGamepadWithTouchpadEvent transformPointToProgram transformHeightToProgram transformWidthToProgram
        onMouseMoved onMouseScrollingDelta dispatchTouchEvent onGenericMotionEvent onCapturedPointer"

# Verbatim extraction of one method declared at class level (4-space indent):
# from its declaration line to the line where its braces balance.
extract() {
    tr -d '\r' < "$1" | awk -v name="$2" '
        !p && $0 ~ "^    (public|private|protected)[^=;(]* " name "\\(" { p = 1 }
        p { print; depth += gsub(/\{/, "{") - gsub(/\}/, "}"); if (depth == 0) exit }'
}

gen() {  # class, base class, source file, methods...
    local cls=$1 base=$2 file=$3 m body
    shift 3
    {
        echo "package harness;"
        echo "import android.graphics.PointF; import android.os.Build; import android.util.Log; import android.view.*;"
        echo "import git.artdeell.skymodloader.ImGUI; import kotlin.KotlinVersion;"
        echo "// GENERATED by run_mouse.sh from $file: verbatim methods, do not edit."
        echo "public class $cls extends $base {"
        tr -d '\r' < "$file" | grep '^    private static final String MOUSE_TAG' || true  # PATCHED only
        for m in "$@"; do
            body=$(extract "$file" "$m")
            [ -n "$body" ] || { echo "EXTRACTION FAILED: $m in $file" >&2; return 1; }
            echo "$body"
        done
        echo "}"
    } > $GEN/harness/$cls.java
}

rm -rf $GEN && mkdir -p $GEN/harness
gen StockMouse GameActivity $STOCK_SRC $COMMON
gen CanvasMouse MouseBase $HEAD_SRC $COMMON updateGameInputOffset submitImGuiMousePosition $HEAD_EXTRA
[ -f "$OLD_SRC" ] && gen Canvas172Mouse MouseBase $OLD_SRC $COMMON
[ -d /stock2 ] && gen Stock0351Mouse GameActivity $STOCK2_SRC $COMMON
rm -rf $OUT/classes && mkdir -p $OUT/classes
javac -nowarn -d $OUT/classes $(find $M/harness -name '*.java') $GEN/harness/*.java
java -cp $OUT/classes harness.Main
